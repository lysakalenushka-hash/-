def join(items) -> str:
    if not items:
        return ""
    if isinstance(items, str):
        return items
    return " ".join(str(x).strip() for x in items if x)


def src0(sources):
    if not sources:
        return "", ""
    name, url = sources[0][0], sources[0][1]
    return name, url


