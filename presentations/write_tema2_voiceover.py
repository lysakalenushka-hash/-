def write_notes(prs: Presentation) -> None:
    if len(prs.slides) != len(SCRIPTS):
        raise RuntimeError(f"Expected {len(SCRIPTS)} slides, got {len(prs.slides)}")
    for slide, text in zip(prs.slides, SCRIPTS):
        notes = slide.notes_slide
        notes.notes_text_frame.text = text.strip()


def write_txt() -> None:
    titles = [
        "Слайд 1. Титул",
        "Слайд 2. Тема 2. Наружные кровотечения",
        "Слайд 3. Опасность кровопотери",
        "Слайд 4. Признаки наружного кровотечения",
        "Слайд 5. Обзорный осмотр пострадавшего",
        "Слайд 6. Прямое давление на рану",
        "Слайд 7. Давящая повязка",
        "Слайд 8. Инородное тело и открытый перелом",
        "Слайд 9. Кровоостанавливающий жгут",
        "Слайд 10. Последовательность остановки кровотечения",
        "Слайд 11. Голова, шея, грудь, живот",
        "Слайд 12. Конечности, отрыв, смежные зоны",
        "Слайд 13. Типичные ошибки при обучении теме",
        "Слайд 14. Благодарим за внимание",
    ]
    blocks = []
    for title, script in zip(titles, SCRIPTS):
        blocks.append(f"{title}\n\n{script.strip()}\n")
    TXT.write_text("\n" + ("-" * 60 + "\n\n").join(blocks), encoding="utf-8")


def main() -> None:
    prs = Presentation(str(PPTX))
    write_notes(prs)
    prs.save(str(PPTX))
    write_txt()
    print(f"Updated notes in {PPTX}")
    print(f"Wrote {TXT}")


if __name__ == "__main__":
    main()
