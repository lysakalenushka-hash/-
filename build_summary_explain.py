def polish_rows(rows: list[list]) -> list[list]:
    out = []
    for row in rows:
        r = list(row)
        while len(r) < 12:
            r.append("")
        subject, topic, metric = r[1], r[2], r[3]
        text, vs_rf, kind, url = r[4], r[7], r[8], r[10]
        key = (subject, metric)
        if key in CUSTOM:
            exp, nir_c = CUSTOM[key]
            if not r[5]:
                r[5] = exp
            if nir_c and not r[6]:
                r[6] = nir_c
        if not r[5]:
            r[5] = default_explain(subject, topic, metric, text, kind)
        if not r[6]:
            r[6] = default_nir(subject, topic, metric, text, vs_rf, kind)
        if not r[11]:
            r[11] = link_note_for(url, metric, subject, kind)
        out.append(r)
    return out
