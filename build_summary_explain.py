def pick_source(d: dict, metric: str) -> tuple[str, str]:
    sources = d.get("sources") or []
    if not sources:
        return "", ""
    idx = (d.get("src_i") or {}).get(metric, 0)
    if not isinstance(idx, int) or idx < 0 or idx >= len(sources):
        idx = 0
    return sources[idx][0], sources[idx][1]


