def _sentences(*parts: str) -> str:
    out = []
    for p in parts:
        p = (p or "").strip()
        if not p:
            continue
        if p[-1] not in ".!?…»:":
            p += "."
        out.append(p)
    return " ".join(out)


def default_explain(subject: str, topic: str, metric: str, text: str, kind: str) -> str:
    t = (text or "").strip()
    if metric == "Особенность ОТ":
        return _sentences(
            f"Это не цитата иностранного закона, а вывод составителя о том, чем охрана труда в «{subject}» отличается от российского журнала инструктажа",
            "Короткая формула в «Содержании» сжата специально; полный смысл — в этом столбце и в «Абзаце для НИР»",
            t,
        )
    if metric == "Особенность модели":
        return _sentences(
            f"Краткая «изюминка» режима ЭДО в «{subject}», а не название статьи закона",
            t,
        )
    if metric == "Что взять":
        return _sentences(
            "Предложение для главы 3: что можно заимствовать в российское регулирование или в требования к информационной системе",
            "Это не действующая норма РФ",
            t,
        )
    if metric == "Что не переносить":
        return _sentences(
            "Ограничение заимствования: что копировать нельзя или рано",
            t,
        )
    if metric == "Сравнение с РФ":
        return _sentences(
            f"Прямое сопоставление «{subject}» с 63‑ФЗ / ст. 22.1–22.3 ТК / ПП 2464",
            t,
        )
    if metric == "Обзор":
        return _sentences(
            f"Сжатый пересказ справки по «{subject}» ({topic}). Это обзор, не диспозиция статьи",
            t,
        )
    if metric in ("Основные акты", "Акты ОТ"):
        return _sentences(
            "Перечень актов, на которые опирается справка. Каждый акт смотрите по URL в этой или соседних строках",
            "Не все перечисленные акты — про ЭДО: часть про охрану труда",
            t,
        )
    if metric in ("Юридическая сила", "Можно ли e‑журнал / e‑учёт"):
        return _sentences(
            "Когда электронная запись признаётся (или, наоборот, журнал нельзя заменить КЭДО)",
            t,
        )
    if metric in ("Модель подписи", "Подпись / форма"):
        return _sentences(
            "Какой вид электронной или собственноручной подписи типичен для этого контура",
            t,
        )
    if metric == "Значение для НИР":
        return _sentences(
            "Зачем эта судебная карточка в главе 3. Если тип «аналогия» — не утверждайте, что суд разрешил или запретил электронный журнал",
            t,
        )
    if metric == "Тип карточки":
        return (
            "«Прямая практика» — спор про электронную подпись / электронный документ. "
            "«Аналогия» — спор про содержание обучения, форму подписи или реквизиты журнала, без вопроса о праве вести журнал в КЭДО."
        )
    if metric in ("Суд", "Цитата", "Сюжет", "Фабула", "Позиция суда"):
        return _sentences(
            f"Фрагмент судебной карточки ({metric.lower()}). Номер дела не вымышлен",
            "Полный сюжет собирается из соседних строк той же юрисдикции на листах «Фабула» и «Позиция суда»",
            t,
        )
    if metric == "Смысл":
        return _sentences("Статья глоссария: термин, который иначе остаётся англицизмом или аббревиатурой", t)
    if metric == "Источник":
        return "Строка не содержит факта, только имя источника. Смысл документа — в URL и в столбце «Что в ссылке»."
    if metric in ("E‑журнал (кратко)", "E‑обучение (кратко)"):
        return (
            f"Короткий статус для матрицы: «да» / «нет» / «частично». "
            f"Для «{subject}»: {t or 'нет данных'}. Расшифровку читайте в строках «Можно ли e‑журнал» и «Обзор»."
        )
    if metric == "РФ: можно ли электронно":
        return _sentences("Ответ матрицы документов ОТ именно для России", t)
    if metric == "За рубежом":
        return _sentences("Как тот же документ ОТ ведут в выборке стран — одним абзацем", t)
    if metric == "Что проверяет суд / инспектор":
        return _sentences(
            "Не носитель, а реквизиты и факт: кто, когда, чему научен, можно ли воспроизвести запись",
            t,
        )
    if not t:
        return f"Показатель «{metric}» по «{subject}» ({topic}). Пустая ячейка «Содержание» — смотрите соседние строки."
    return _sentences(
        f"Показатель «{metric}» по «{subject}»",
        "Ниже — тот же смысл развёрнуто, без телеграфа",
        t,
    )


