def set_run(run, *, bold=False, size=12):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(size)
    run.bold = bold


def add_para(doc, text, *, bold=False, size=12, align=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=True):
    p = doc.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    pf.line_spacing = 1.15
    pf.space_after = Pt(4)
    pf.first_line_indent = Cm(1.0) if indent and align == WD_ALIGN_PARAGRAPH.JUSTIFY else Cm(0)
    run = p.add_run(text)
    set_run(run, bold=bold, size=size)
    return p


def add_heading(doc, text):
    add_para(doc, text, bold=True, size=13, indent=False)


def add_table(doc, headers, rows):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = h
        for p in cell.paragraphs:
            for r in p.runs:
                set_run(r, bold=True, size=11)
    for row in rows:
        cells = table.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = val
            for p in cells[i].paragraphs:
                for r in p.runs:
                    set_run(r, size=11)
    return table


