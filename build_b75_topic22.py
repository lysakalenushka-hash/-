def set_run(run, *, bold=False, size=12):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(size)
    run.bold = bold


def add_para(doc, text, *, bold=False, size=12, center=False, indent=True):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.JUSTIFY
    pf = p.paragraph_format
    pf.line_spacing = 1.15
    pf.space_after = Pt(6)
    pf.first_line_indent = Cm(1.25) if indent and not center else Cm(0)
    run = p.add_run(text)
    set_run(run, bold=bold, size=size)


def add_bullet(doc, text):
    p = doc.add_paragraph(style="List Paragraph")
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf = p.paragraph_format
    pf.line_spacing = 1.15
    pf.space_after = Pt(3)
    pf.left_indent = Cm(1.25)
    run = p.add_run(text)
    set_run(run, size=12)


def add_table(doc, headers, rows):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = h
        for p in cell.paragraphs:
            for r in p.runs:
                set_run(r, bold=True, size=11)
    for row in rows:
        cells = table.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = val
            for p in cells[i].paragraphs:
                for r in p.runs:
                    set_run(r, size=11)


def build():
    doc = Document()
    for s in doc.sections:
        s.top_margin = Cm(2)
        s.bottom_margin = Cm(2)
        s.left_margin = Cm(2.5)
        s.right_margin = Cm(1.5)

    add_para(
        doc,
        "МОДУЛЬ 2. ПРОЕКТИРОВАНИЕ СЕТЕЙ ГАЗОРАСПРЕДЕЛЕНИЯ И ГАЗОПОТРЕБЛЕНИЯ",
        bold=True,
        center=True,
        indent=False,
    )
    doc.add_paragraph()
    add_para(
        doc,
        "Тема 2.2. Требования к проектированию: трассы, материалы, ГРП/ГРУ, вентиляция, КИП",
        bold=True,
        indent=False,
    )
    doc.add_paragraph()

    for text in INTRO:
        add_para(doc, text)

    add_para(
        doc,
        "Организация, осуществляющая проектирование сетей газораспределения "
        "и газопотребления, обеспечивает:",
        indent=False,
    )
    for item in ORG:
        add_bullet(doc, item)

    for heading, paragraphs in SECTIONS:
        doc.add_paragraph()
        add_para(doc, heading, bold=True, indent=False)
        doc.add_paragraph()
        for text in paragraphs:
            add_para(doc, text)

    doc.add_paragraph()
    add_para(doc, "Соотношение темы и нормативных документов", bold=True, indent=False)
    doc.add_paragraph()
    add_table(
        doc,
        ["Раздел темы", "Документ", "Пункты"],
        SOURCE_MAP,
    )

    doc.save(OUT)
    print(f"Created: {OUT}")


if __name__ == "__main__":
    build()
