RED = RGBColor(0xE3, 0x06, 0x13)
DARK = RGBColor(0x1A, 0x1A, 0x1A)
GRAY = RGBColor(0x6B, 0x72, 0x80)
AMBER = RGBColor(0xF5, 0x9E, 0x0B)

TEXT_W = Emu(11000000)


def set_run(run, size_pt, bold=False, color=DARK):
    run.font.name = "Inter"
    run.font.size = Pt(size_pt)
    run.font.bold = bold
    run.font.color.rgb = color


def set_text(shape, text, size_pt=13, bold=False, color=DARK):
    tf = shape.text_frame
    tf.clear()
    p = tf.paragraphs[0]
    r = p.add_run()
    r.text = text
    set_run(r, size_pt, bold=bold, color=color)


def text_shapes(slide):
    return [s for s in slide.shapes if s.has_text_frame and s.text_frame.text.strip()]


def clear_slides(prs):
    while len(prs.slides) > 0:
        r_id = prs.slides._sldIdLst[0].rId
        prs.part.drop_rel(r_id)
        del prs.slides._sldIdLst[0]


def make_slide(prs, shape_elements):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    for shape in list(slide.shapes):
        shape.element.getparent().remove(shape.element)
    for element in shape_elements:
        slide.shapes._spTree.insert_element_before(deepcopy(element), "p:extLst")
    return slide


def update_pages(prs):
    total = len(prs.slides)
    for i, slide in enumerate(prs.slides, 1):
        page_shape = None
        for sh in slide.shapes:
            if not sh.has_text_frame:
                continue
            # Prefer footer page badge by position (bottom-right)
            if sh.top > Emu(6200000) and sh.left > Emu(8000000):
                page_shape = sh
                break
        if page_shape is None:
            for sh in text_shapes(slide):
                t = sh.text_frame.text.strip()
                if " / " in t:
                    left, right = [x.strip() for x in t.split(" / ", 1)]
                    if left.isdigit() and right.isdigit():
                        page_shape = sh
                        break
        if page_shape is not None:
            set_text(page_shape, f"{i:02d} / {total:02d}", 9, True, RED)


def is_page_shape(shape):
    t = shape.text_frame.text.strip()
    if " / " in t:
        left, right = [x.strip() for x in t.split(" / ", 1)]
        if left.isdigit() and right.isdigit():
            return True
    return shape.top > Emu(6200000) and shape.left > Emu(8000000)


def fill_text_slide(slide, section, title, intro, body, note=None):
    shapes = sorted(text_shapes(slide), key=lambda s: (s.top, s.left))
    set_text(shapes[0], section, 11, True, RED)
    set_text(shapes[1], title, 26, True, DARK)
    set_text(shapes[2], intro, 12, False, GRAY)
    set_text(shapes[3], body, 13, False, DARK)
    # Do not clear page-number shape (can be shapes[4] when footer is empty)
    if len(shapes) > 4 and not is_page_shape(shapes[4]):
        set_text(shapes[4], "", 11, False, GRAY)
    if note:
        for sh in shapes:
            if is_page_shape(sh):
                continue
            if sh.top > Emu(5800000) and sh.left < Emu(5000000):
                set_text(sh, note, 12, True, AMBER)
                break


def fill_list_slide(slide, section, title, intro, list_title, items, note=None):
    shapes = sorted(text_shapes(slide), key=lambda s: (s.top, s.left))
    set_text(shapes[0], section, 11, True, RED)
    set_text(shapes[1], title, 26, True, DARK)
    set_text(shapes[2], intro, 12, False, GRAY)
    set_text(shapes[3], list_title, 11, True, RED)

    pairs = []
    more_shape = None
    for sh in shapes[5:]:
        t = sh.text_frame.text.strip()
        if t in {f"{i:02d}" for i in range(1, 10)}:
            pairs.append([sh, None])
        elif pairs and pairs[-1][1] is None:
            pairs[-1][1] = sh
        elif t.startswith("…"):
            more_shape = sh

    for i, item in enumerate(items[:4]):
        if i < len(pairs):
            set_text(pairs[i][0], f"{i+1:02d}", 14, True, RED)
            set_text(pairs[i][1], item, 12, False, DARK)

    for i in range(len(items[:4]), len(pairs)):
        set_text(pairs[i][0], "", 14, True, RED)
        set_text(pairs[i][1], "", 14, False, DARK)

    if more_shape:
        rest = max(0, len(items) - 4)
        set_text(more_shape, f"… ещё {rest}" if rest else "", 9, False, GRAY)

    if note:
        for sh in shapes:
            if sh.top > Emu(5900000) and sh.left > Emu(700000):
                set_text(sh, note, 12, True, AMBER)
                break


def add_definition_block(slide, items, start_top=Emu(2000000), width=None):
    top = start_top
    w = width or TEXT_W
    for term, definition in items:
        box = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Emu(548640), top, w, Emu(780000))
        box.fill.solid()
        box.fill.fore_color.rgb = RGBColor(0xFA, 0xFA, 0xFA)
        box.line.color.rgb = RGBColor(0xE5, 0xE7, 0xEB)
        box.line.width = Pt(0.75)
        tf = slide.shapes.add_textbox(
            Emu(640000), top + Emu(60000), w - Emu(120000), Emu(680000)
        ).text_frame
        tf.clear()
        tf.word_wrap = True
        p = tf.paragraphs[0]
        r1 = p.add_run()
        r1.text = f"{term} — "
        set_run(r1, 12, True, RED)
        r2 = p.add_run()
        r2.text = definition
        set_run(r2, 11, False, GRAY)
        top += Emu(860000)


