MOD = "МОДУЛЬ 4"


def save(prs, name):
    path = f"/workspace/{name}"
    prs.save(path)
    print("saved", path, "slides", len(prs.slides))


def kw(topic, total):
    return dict(topic=topic, total=total, module=MOD)


def ft(s, n, total, topic):
    footer(s, n, total, topic, MOD)


def closer(prs, total, topic, text, next_t=None):
    s = new_slide(prs)
    add_text(s, 0.7, 2.3, 12, 2.4, text, size=28, color=NAVY, name=SERIF)
    if next_t:
        add_text(s, 0.7, 5.1, 12, 0.5, next_t, size=18, color=MUTED)
    ft(s, total, total, topic)


