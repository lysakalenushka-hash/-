def write_cell(ws, r, c, value, *, font, fill=None):
    cell = ws.cell(r, c, value)
    cell.font = font
    cell.alignment = ALIGN
    cell.border = THIN
    if fill is not None:
        cell.fill = fill
    return cell


def build():
    shutil.copy2(SOURCE, OUTPUT)
    wb = load_workbook(OUTPUT)

    ws_t = wb["Test"]
    ws_t.cell(2, 1).value = (
        'Итоговое тестирование по курсу "Б.7.5 Проектирование, строительство, '
        "реконструкция, техническое перевооружение и капитальный ремонт сетей "
        'газораспределения и газопотребления"'
    )
    ws_t.cell(2, 2).value = (
        "Уважаемый слушатель! Сейчас Вам необходимо пройти проверку знаний по результатам "
        "пройденного обучения. Тест состоит из 20 вопросов, ответить на которые необходимо "
        "в течение 20 минут. Для успешного прохождения теста необходимо дать правильные "
        "ответы на 18 вопросов. Желаем удачи!"
    )
    ws_t.cell(2, 3).value = 18
    ws_t.cell(2, 4).value = 90
    ws_t.cell(2, 5).value = 2
    ws_t.cell(2, 6).value = 1200

    ws_p = wb["Parts"]
    ws_p.cell(2, 1).value = FOLDER
    ws_p.cell(2, 2).value = 20

    ws = wb["Questions"]
    if ws.max_row > 1:
        ws.delete_rows(2, ws.max_row - 1)

    row = 2
    for num, item in enumerate(QUESTIONS, 1):
        n_ok = sum(1 for _, f in item["answers"] if f)
        write_cell(ws, row, 1, FOLDER, font=FONT_Q, fill=YELLOW)
        write_cell(ws, row, 2, num, font=FONT_Q)
        write_cell(ws, row, 3, "Вопрос", font=FONT_Q)
        write_cell(ws, row, 4, item["q"], font=FONT_Q)
        write_cell(ws, row, 5, n_ok, font=FONT_Q)
        write_cell(ws, row, 6, item.get("comment") or None, font=FONT_A)
        write_cell(ws, row, 7, None, font=FONT_A)
        write_cell(ws, row, 8, "Текст", font=FONT_Q)
        write_cell(ws, row, 9, " ", font=FONT_A)
        ws.row_dimensions[row].height = 51
        row += 1
        for text, flag in item["answers"]:
            write_cell(ws, row, 1, FOLDER, font=FONT_Q, fill=YELLOW)
            write_cell(ws, row, 2, num, font=FONT_A)
            write_cell(ws, row, 3, "Ответ", font=FONT_A)
            write_cell(ws, row, 4, text, font=FONT_A)
            write_cell(ws, row, 5, flag, font=FONT_A)
            write_cell(ws, row, 9, " ", font=FONT_A)
            ws.row_dimensions[row].height = 30
            row += 1

    wb.save(OUTPUT)
    print(f"Saved {OUTPUT}: {len(QUESTIONS)} questions, {row - 2} data rows")


if __name__ == "__main__":
    build()
