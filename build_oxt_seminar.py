        doc,
        "Процесс 1: T1 = 298 К, Kp1 = 17,5.  ΔH = −26000 Дж/моль (не зависит от T),\n"
        "ΔS тоже не зависит от T.  Процесс 2: T2 = 348 К.",
        "Во сколько раз изменится равновесная степень превращения.",
