    given_find(
        doc,
        "T = 298 К;  ΔH = −30,5 кДж/моль;  ΔS = −80 кДж/(кмоль·К) = −80 Дж/(моль·К).\n"
        "Сравнить xA* при  (1) CA0/CB0 = 0,5  и  (2) CA0/CB0 = 0,25.",
        "Отношение xA1* / xA2*.",
    )
    P(
        doc,
        "    ΔG = −30500 − 298 · (−80) = −30500 + 23840 = −6660 Дж/моль.\n"
        "    K = exp(6660 / (8,314 · 298)) = exp(2,688) = 14,70.\n"
        "Δν = 0, Kc = CR*² / (CA* CB*) = K.\n"
        "Обозначим r = CA0 / CB0, x = xA*. Тогда\n"
        "    CA* = CA0 (1 − x),  CB* = CB0 − CA0 x = CB0 (1 − r x),  CR* = 2 CA0 x,\n"
        "    K = 4 r x² / [ (1 − x)(1 − r x) ].\n"
        "При r = 0,5 уравнение даёт x1* = 0,836.\n"
        "При r = 0,25 уравнение даёт x2* = 0,924.\n"
        "    x1* / x2* = 0,836 / 0,924 = 0,905.\n"
        "Избыток B (меньший r) увеличивает степень превращения дефицитного A.",
    )
    Ans(doc, "xA1* меньше xA2* в 0,905 раза.")

    H2(doc, "Пример 5.   A + B ↔ 2R")
    given_find(
        doc,
        "T = 500 К. Прямая и обратная реакции 2-го порядка.\n"
        "k1 = 6,2·10⁴ exp(−27600 / RT),   k−1 = 7,5·10⁵ exp(−32000 / RT).\n"
        "CA0 = 2 моль/л;  CB0 = 2,5 моль/л.",
        "Равновесный состав.",
    )
    P(
        doc,
        "    k1(500) = 6,2·10⁴ · exp(−27600 / (8,314·500)) = 6,2·10⁴ · exp(−6,639) = 81,08,\n"
        "    k−1(500) = 7,5·10⁵ · exp(−32000 / (8,314·500)) = 7,5·10⁵ · exp(−7,698) = 340,3.\n"
        "Для реакций одного порядка  Kc = k1 / k−1 = 81,08 / 340,3 = 0,238.\n"
        "Пусть ξ — убыль A (моль/л):  CA* = 2 − ξ,  CB* = 2,5 − ξ,  CR* = 2ξ.\n"
        "    Kc = (2ξ)² / [(2 − ξ)(2,5 − ξ)] = 0,238,\n"
        "    4ξ² = 0,238 (2 − ξ)(2,5 − ξ).\n"
        "Корень на (0; 2):  ξ = 0,438.\n"
        "    CA* = 2 − 0,438 = 1,56 моль/л,\n"
        "    CB* = 2,5 − 0,438 = 2,06 моль/л,\n"
        "    CR* = 2 · 0,438 = 0,88 моль/л.",
    )
    Ans(doc, "CA* = 1,56 моль/л;   CB* = 2,06 моль/л;   CR* = 0,88 моль/л.")

    H2(doc, "Пример 6.   A + 2B ↔ 3R")
    given_find(
        doc,
        "T = 373 К;  ΔG = −11,2 кДж/моль;  CA0 = 1 моль/л;  CB0 = 2 моль/л.",
        "xA* и равновесный состав.",
    )
    P(
        doc,
        "    K = exp(−ΔG / RT) = exp(11200 / (8,314 · 373)) = exp(3,612) = 37,03.\n"
        "Смесь стехиометрическая. Пусть x = xA*:\n"
        "    CA* = 1 − x,   CB* = 2 − 2x,   CR* = 3x.\n"
        "Δν = 0, поэтому\n"
        "    K = CR*³ / (CA* CB*²) = 27 x³ / [ (1 − x) · 4 (1 − x)² ] = (27/4) [x / (1 − x)]³.\n"
        "    x / (1 − x) = (37,03 · 4 / 27)^{1/3} = 1,763,\n"
        "    x* = 1,763 / 2,763 = 0,638 ≈ 0,64.\n"
        "    CA* = 1 − 0,64 = 0,36 моль/л,\n"
        "    CB* = 2 − 2·0,64 = 0,72 моль/л,\n"
        "    CR* = 3 · 0,64 = 1,92 моль/л.",
    )
    Ans(doc, "xA* = 0,64;   CA* = 0,36;   CB* = 0,72;   CR* = 1,92 моль/л.")

    # =====================================================================
    H1(doc, "Часть III. Кинетика")
    P(
        doc,
        "Аррениус:  k = k0 exp(−Ea / RT).\n"
        "Связь скоростей по компонентам:  w_i / ν_i = w_j / ν_j.\n"
        "Второй порядок A + B при CA0 = CB0:  1/C − 1/C0 = k t.\n"
        "Параллельные реакции 1-го порядка A → продукты:\n"
        "    CA = CA0 exp[−(k1 + k2) t],   продукты делятся пропорционально ki.\n"
        "Последовательные A → R → S (1-й порядок):\n"
        "    CA = CA0 e^{−k1 t},\n"
        "    CR = CA0 k1/(k2 − k1) ( e^{−k1 t} − e^{−k2 t} ),\n"
        "    CS = CA0 − CA − CR.\n"
        "Интегральная селективность:  SR = CR / (CA0 − CA).\n"
        "Дифференциальная:  SR′ = wR / (−wA).",
        size=13,
        italic=True,
    )

    H2(doc, "Пример 2.   A + B → R")
    given_find(
        doc,
        "k = 100 л/(моль·ч);  CA0 = CB0 = 0,08 моль/л;  в конце CA = CB = 0,04 моль/л.",
        "Время процесса t.",
    )
    P(
        doc,
        "Реакция 2-го порядка, концентрации A и B всё время равны:\n"
        "    − dC/dt = k C²  ⇒  1/C − 1/C0 = k t.\n"
        "    1/0,04 − 1/0,08 = 25 − 12,5 = 12,5 л/моль,\n"
        "    t = 12,5 / 100 = 0,125 ч = 0,125 · 3600 с = 450 с.",
    )
    Ans(doc, "t = 450 с.")

    H2(doc, "Пример 3. Влияние катализатора")
    given_find(
        doc,
        "Ea = 75,24 кДж/моль без катализатора;  Eaкт = 50,14 кДж/моль с катализатором;  T = 298 К.\n"
        "Предэкспонента k0 считается одинаковой.",
        "Отношение скоростей rкт / r.",
    )
    P(
        doc,
        "    k = k0 exp(−Ea / RT),   rкт / r = kкт / k = exp[ −(Eaкт − Ea) / RT ]\n"
        "       = exp[ (75240 − 50140) / (8,314 · 298) ]\n"
        "       = exp( 25100 / 2477,6 ) = exp(10,131) = 25106.\n"
        "Катализатор ускоряет реакцию в 25106 раз.",
    )
    Ans(doc, "rкт / r = 25106.")

    H2(doc, "Пример 4. Энергия активации")
    given_find(
        doc,
        "Скорость при 300 К в 10 раз больше, чем при 298 К.",
        "Ea.",
    )
    P(
        doc,
        "    ln(k2/k1) = (Ea/R) (1/T1 − 1/T2),\n"
        "    ln 10 = (Ea / 8,314) · (1/298 − 1/300),\n"
        "    2,302585 = (Ea / 8,314) · 2,2371·10⁻⁵,\n"
        "    Ea = 2,302585 · 8,314 / 2,2371·10⁻⁵ = 8,556·10⁵ Дж/моль = 855,88 кДж/моль.",
    )
    Ans(doc, "Ea = 855,88 кДж/моль.")

    H2(doc, "Пример 5.   2A + 3B → S + 4R + 2F")
