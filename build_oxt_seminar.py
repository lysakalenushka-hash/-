        "Δν = 0, поэтому Kc = K = (CR* CS*) / (CA* CB*).\n"
        "Пусть x* — степень превращения A. Тогда CR* = CS* = CA0 x*,  CA* = CB* = CA0 (1 − x*),\n"
        "    K = [x* / (1 − x*)]² = 1,782  ⇒  x* / (1 − x*) = √1,782 = 1,335,\n"
        "    x* = 1,335 / 2,335 = 0,572.\n"
        "    CR* = CS* = 1,5 · 0,572 = 0,858 ≈ 0,855 моль/л,\n"
        "    CA* = CB* = 1,5 · 0,428 = 0,642 ≈ 0,645 моль/л.",
