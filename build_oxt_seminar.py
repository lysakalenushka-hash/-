#!/usr/bin/env python3
"""Решения задач ОХТ: стехиометрия, термодинамика, кинетика."""

from __future__ import annotations

import shutil
from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor

OUT = Path("/workspace/oxt_seminar/OXT_resheniya_zadach.docx")
OUT_CYR = Path("/workspace/oxt_seminar/ОХТ_решения_задач.docx")


def set_run(run, size=14, bold=False, italic=False, color=None):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = RGBColor(*color)


def P(doc, text, size=14, bold=False, italic=False, color=None, after=6, before=0):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.line_spacing = 1.15
    run = p.add_run(text)
    set_run(run, size=size, bold=bold, italic=italic, color=color)
    return p


def H1(doc, text):
    P(doc, text, size=16, bold=True, color=(31, 78, 121), before=12, after=8)


def H2(doc, text):
    P(doc, text, size=14, bold=True, color=(46, 117, 182), before=10, after=4)


def Ans(doc, text):
    P(doc, "Ответ: " + text, size=14, bold=True, after=10)


def build():
    doc = Document()
    for s in doc.sections:
        s.top_margin = Cm(1.6)
        s.bottom_margin = Cm(1.6)
        s.left_margin = Cm(2.0)
        s.right_margin = Cm(1.5)

    P(doc, "Основы химической технологии. Семинары", size=18, bold=True, after=2)
    P(doc, "Решения задач: стехиометрия, термодинамика, кинетика", size=14, italic=True, after=12)
    P(
        doc,
        "Расчёты по формулам семинара. R = 8,314 Дж/(моль·К). "
        "Ответы сверены с числами в бланках задач.",
        size=12,
        after=10,
    )

    # ========== СТЕХИОМЕТРИЯ ==========
    H1(doc, "I. Стехиометрия")
    P(
        doc,
        "Метод. Для каждой реакции вводим степень протекания ξ (моль/л при V = const). "
        "C_i = C_i0 + Σ ν_ij ξ_j. Степень превращения x_B = (C_B0 − C_B)/C_B0. "
        "Выход E_P = (ν_B/ν_P) · C_P / C_B0.",
        size=13,
        italic=True,
    )

    H2(doc, "Задача 1")
    P(
        doc,
        "A + B → R + D    (ξ1)\n"
        "2B → P            (ξ2)\n"
        "2R → S            (ξ3)\n"
        "CA0 = 0,1 моль/л; CB0 = 0,3 моль/л; CP = 0,028; CS = 0,012; CD = 0,034.",
    )
    P(
        doc,
        "Из балансов продуктов: CD = ξ1 ⇒ ξ1 = 0,034;  CP = ξ2 ⇒ ξ2 = 0,028;  CS = ξ3 ⇒ ξ3 = 0,012.\n"
        "CR = ξ1 − 2ξ3 = 0,034 − 2·0,012 = 0,010 моль/л.\n"
        "Израсходовано B: ΔCB = ξ1 + 2ξ2 = 0,034 + 0,056 = 0,090 моль/л.\n"
        "xB = 0,090 / 0,3 = 0,30.\n"
        "Для 2B → P максимум P равен CB0/2 = 0,15;  EP = 0,028 / 0,15 = 0,187.",
    )
    Ans(doc, "CR = 0,01 моль/л;  xB = 0,30;  EP = 0,187.")

    H2(doc, "Задача 2")
    P(
        doc,
        "A + B → R          (ξ1)\n"
        "2A → S             (ξ2)\n"
        "2S + B → T + 2D    (ξ3)\n"
        "R + A → T          (ξ4)\n"
        "CA0 = 2; CB0 = 1,7; CA = 0,1; CB = 0,5; CT = 0,15; CD = 0,05.",
    )
    P(
        doc,
        "CD = 2ξ3 ⇒ ξ3 = 0,025.\n"
        "CB: CB0 − ξ1 − ξ3 = 0,5 ⇒ ξ1 + 0,025 = 1,2 ⇒ ξ1 = 1,175.\n"
        "CT: ξ3 + ξ4 = 0,15 ⇒ ξ4 = 0,125.\n"
        "CA: CA0 − ξ1 − 2ξ2 − ξ4 = 0,1 ⇒ 2 − 1,175 − 2ξ2 − 0,125 = 0,1 ⇒ 2ξ2 = 0,6 ⇒ ξ2 = 0,3.\n"
        "CR = ξ1 − ξ4 = 1,175 − 0,125 = 1,05 моль/л.\n"
        "CS = ξ2 − 2ξ3 = 0,3 − 0,050 = 0,25 моль/л.",
    )
    Ans(doc, "CR = 1,05 моль/л;  CS = 0,25 моль/л.")

    H2(doc, "Задача 3")
    P(
        doc,
        "A + 2B → R         (ξ1)\n"
        "R + B → S          (ξ2)\n"
        "3B → 2T            (ξ3)\n"
        "2A + B → S + D     (ξ4)\n"
        "CA0 = 1; CA = 0,44; CR = 0,05; CS = 0,33; CT = 0,14; B прореагировал полностью.",
    )
    P(
        doc,
        "CT = 2ξ3 ⇒ ξ3 = 0,07.\n"
        "CR = ξ1 − ξ2 = 0,05  ⇒  ξ1 = 0,05 + ξ2.\n"
        "CS = ξ2 + ξ4 = 0,33  ⇒  ξ2 = 0,33 − ξ4.\n"
        "CA: 1 − ξ1 − 2ξ4 = 0,44 ⇒ ξ1 + 2ξ4 = 0,56.\n"
        "Подстановка: 0,05 + (0,33 − ξ4) + 2ξ4 = 0,56 ⇒ 0,38 + ξ4 = 0,56 ⇒ ξ4 = 0,18.\n"
        "ξ2 = 0,15;  ξ1 = 0,20.\n"
        "CD = ξ4 = 0,18 моль/л.\n"
        "CB0 = 2ξ1 + ξ2 + 3ξ3 + ξ4 = 0,40 + 0,15 + 0,21 + 0,18 = 0,94 моль/л.",
    )
    Ans(doc, "CB0 = 0,94 моль/л;  CD = 0,18 моль/л.")

    # ========== ТЕРМОДИНАМИКА ==========
    H1(doc, "II. Термодинамика")
    P(
        doc,
        "ΔG = ΔH − TΔS;  K = exp(−ΔG / RT). При Δν = 0 для жидкой фазы Kc = Kp = K. "
        "van’t Hoff: ln(K2/K1) = −(ΔH/R)·(1/T2 − 1/T1).",
        size=13,
        italic=True,
    )

    H2(doc, "Пример 1.  A ↔ 2R")
    P(
        doc,
        "Kc = 1,33 моль/л; CA0 = 2 моль/л; xA = (3/4)·xA*.",
    )
    P(
        doc,
        "Kc = CR*² / CA* = (2 CA0 x*)² / [CA0(1 − x*)] = 8 x*² / (1 − x*).\n"
        "1,33(1 − x*) = 8 x*²  ⇒  8x*² + 1,33x* − 1,33 = 0.\n"
        "x* = [−1,33 + √(1,33² + 42,56)] / 16 = 0,333.\n"
        "xA = 0,75 · 0,333 = 0,25.\n"
        "Равновесный выход по определению семинара E_R* = Δn_R / (2 n_A0) = x* = 0,33. "
        "В бланке указано 0,75 — это заданная доля от x* (¾), не выход. "
        "Если выход считать как CR*/CA0 = 2x*, получится 0,67.",
    )
    Ans(doc, "xA = 0,25;  xA* = 0,33.  (В бланке ER* = 0,75 — это ¾ от равновесия.)")

    H2(doc, "Пример 2.  A + B ↔ R + S,  T = 330 К")
    P(
        doc,
        "ΔH = −59500 кДж/кмоль; ΔS = −175,5 кДж/(кмоль·К); CA0 = CB0 = 1,5 моль/л.",
    )
    P(
        doc,
        "ΔG = ΔH − TΔS = −59500 − 330·(−175,5) = −59500 + 57915 = −1585 кДж/кмоль.\n"
        "K = exp(−ΔG/RT) = exp(1585 / (8,314·330)) = exp(0,578) = 1,78.\n"
        "Δν = 0, Kc = (x*/(1 − x*))² = 1,78  ⇒  x*/(1 − x*) = 1,335  ⇒  x* = 0,572.\n"
        "CR* = CS* = 1,5 · 0,572 = 0,86 моль/л;  CA* = CB* = 1,5 · 0,428 = 0,64 моль/л.",
    )
    Ans(doc, "CR* = CS* = 0,855 моль/л;  CA* = CB* = 0,645 моль/л.")

    H2(doc, "Пример 3.  A ↔ R")
    P(
        doc,
        "T1 = 298 К, Kp1 = 17,5; ΔH = −26000 Дж/моль; T2 = 348 К. На сколько изменится xA*.",
    )
    P(
        doc,
        "x1* = K1/(1+K1) = 17,5/18,5 = 0,946.\n"
        "ln(K2/K1) = −(ΔH/R)(1/348 − 1/298) = −(−26000/8,314)·(−0,000482) = −1,507.\n"
        "K2 = 17,5 · e^(−1,507) = 3,87.\n"
        "x2* = 3,87/4,87 = 0,795.\n"
        "x1*/x2* = 0,946/0,795 = 1,19.",
    )
    Ans(doc, "xA*(298) больше xA*(348) в 1,19 раза.")

    H2(doc, "Пример 4.  A + B ↔ 2R")
    P(
        doc,
        "T = 298 К; ΔH = −30,5 кДж/моль; ΔS = −80 кДж/(кмоль·К). "
        "Сравнить xA* при CA0/CB0 = 0,5 и 0,25.",
    )
    P(
        doc,
        "ΔG = −30500 − 298·(−80) = −6660 Дж/моль.\n"
        "K = exp(6660/(8,314·298)) = 14,70.\n"
        "Kc = 4 r x² / [(1 − x)(1 − r x)],  r = CA0/CB0.\n"
        "При r = 0,5: x1* = 0,836;  при r = 0,25: x2* = 0,924.\n"
        "x1*/x2* = 0,905.",
    )
    Ans(doc, "xA1* меньше xA2* в 0,905 раза (избыток B повышает xA*).")

    H2(doc, "Пример 5.  A + B ↔ 2R,  T = 500 К")
    P(
        doc,
        "k1 = 6,2·10⁴ exp(−27600/RT);  k−1 = 7,5·10⁵ exp(−32000/RT); "
        "CA0 = 2; CB0 = 2,5 моль/л. Обе реакции 2-го порядка.",
    )
    P(
        doc,
        "k1(500) = 81,08;  k−1(500) = 340,3;  Kc = k1/k−1 = 0,238.\n"
        "Kc = CR*² / (CA* CB*),  CA* = 2 − ξ, CB* = 2,5 − ξ, CR* = 2ξ.\n"
        "4ξ² = 0,238 (2 − ξ)(2,5 − ξ)  ⇒  ξ = 0,438.\n"
        "CA* = 1,56; CB* = 2,06; CR* = 0,88 моль/л.",
    )
    Ans(doc, "CA* = 1,56;  CB* = 2,06;  CR* = 0,88 моль/л.")

    H2(doc, "Пример 6.  A + 2B ↔ 3R,  T = 373 К")
    P(doc, "ΔG = −11,2 кДж/моль; CA0 = 1; CB0 = 2 моль/л (стехиометрическая смесь).")
    P(
        doc,
        "K = exp(11200/(8,314·373)) = 37,03.\n"
        "CA* = 1 − x; CB* = 2 − 2x; CR* = 3x;  Δν = 0.\n"
        "K = 27x³ / [(1 − x)(2 − 2x)²] = (27/4)[x/(1 − x)]³.\n"
        "x/(1 − x) = (37,03 · 4/27)^(1/3) = 1,763  ⇒  x* = 0,64.\n"
        "CA* = 0,36; CB* = 0,72; CR* = 1,92 моль/л.",
    )
    Ans(doc, "xA* = 0,64;  CA* = 0,36;  CB* = 0,72;  CR* = 1,92 моль/л.")

    # ========== КИНЕТИКА ==========
    H1(doc, "III. Кинетика")
    P(
        doc,
        "Аррениус: k = k0 exp(−Ea/RT). Для A+B при CA0=CB0: 1/C − 1/C0 = kt. "
        "Параллельные 1-го порядка: CA = CA0 e^−(k1+k2)t; продукты делятся в отношении констант. "
        "Последовательные A→R→S: CA = CA0 e^−k1 t; "
        "CR = CA0 k1/(k2−k1) (e^−k1t − e^−k2t).",
        size=13,
        italic=True,
    )

    H2(doc, "Пример 2.  A + B → R")
    P(doc, "k = 100 л/(моль·ч); CA0 = CB0 = 0,08; CA = CB = 0,04 моль/л.")
    P(
        doc,
        "Второй порядок, равные концентрации: 1/C − 1/C0 = k t.\n"
        "1/0,04 − 1/0,08 = 12,5 л/моль.\n"
        "t = 12,5 / 100 = 0,125 ч = 0,125 · 3600 = 450 с.",
    )
    Ans(doc, "t = 450 с.")

    H2(doc, "Пример 3. Катализатор")
    P(doc, "Ea = 75,24 кДж/моль без катализатора; 50,14 кДж/моль с катализатором; T = 298 К.")
    P(
        doc,
        "При одинаковом k0:  rкт / r = exp[−(Eaкт − Ea)/RT] = exp[(75240 − 50140)/(8,314·298)]\n"
        "= exp(25100 / 2477,6) = exp(10,13) = 25106.",
    )
    Ans(doc, "rкт / r = 25106 (с катализатором быстрее).")

    H2(doc, "Пример 4")
    P(doc, "r(300 К) / r(298 К) = 10. Найти Ea.")
    P(
        doc,
        "ln 10 = (Ea/R)(1/298 − 1/300)\n"
        "2,3026 = Ea/8,314 · 2,237·10⁻⁵\n"
        "Ea = 2,3026 · 8,314 / 2,237·10⁻⁵ = 855880 Дж/моль = 855,88 кДж/моль.",
    )
    Ans(doc, "Ea = 855,88 кДж/моль.")

    H2(doc, "Пример 5.  2A + 3B → S + 4R + 2F")
    P(doc, "wA = −5 моль/(л·с).")
    P(
        doc,
        "w_i / ν_i = wA / (−2) = 2,5 моль/(л·с).\n"
        "wB = −3 · 2,5 = −7,5;  wS = 2,5;  wR = 10;  wF = 5 моль/(л·с).",
    )
    Ans(doc, "wB = −7,5;  wS = 2,5;  wR = 10;  wF = 5 моль/(л·с).")

    H2(doc, "Пример 6.  A → 2R;  A → S")
    P(doc, "k1 = 0,28 мин⁻¹; k2 = 0,12 мин⁻¹; CA = 2,6; CR = 2,8 моль/л.")
    P(
        doc,
        "CR = 2 k1/(k1+k2) (CA0 − CA) = 2·0,28/0,40 · (CA0 − 2,6)\n"
        "2,8 = 1,4 (CA0 − 2,6) ⇒ CA0 − 2,6 = 2 ⇒ CA0 = 4,6 моль/л.\n"
        "xA = 2 / 4,6 = 0,435 ≈ 0,44.\n"
        "CS = k2/(k1+k2) · 2 = 0,12/0,40 · 2 = 0,60 моль/л.\n"
        "t = −ln(CA/CA0)/(k1+k2) = −ln(2,6/4,6)/0,40 = 1,43 мин.",
    )
    Ans(doc, "xA = 0,44;  CS = 0,60 моль/л;  t = 1,43 мин.")

    H2(doc, "Пример 7.  A → R → S")
    P(doc, "k1 = 0,2 с⁻¹; k2 = 0,1 с⁻¹; CA0 = 1,8 моль/л; xA = 0,9.")
    P(
        doc,
        "CA/CA0 = 0,1 = e^(−k1 t) ⇒ t = ln(10)/0,2 = 11,51 с.\n"
        "CR = CA0 k1/(k2−k1) (e^−k1t − e^−k2t) = 1,8·0,2/(−0,1)·(0,1 − 0,3162) = 0,78 моль/л.\n"
        "Интегральная SR = CR / (CA0 − CA) = 0,78 / 1,62 = 0,48.\n"
        "Дифференциальная SR′ = wR /(−wA) = 1 − k2 CR/(k1 CA) = 1 − 0,1·0,78/(0,2·0,18) = −1,17.",
    )
    Ans(doc, "CR = 0,78 моль/л;  SR = 0,48;  SR′ = −1,17.")

    H2(doc, "Пример 8.  A → 2R;  A → 3S")
    P(doc, "k1 = 1,8 мин⁻¹; k2 = 1,2 мин⁻¹; CA0 = 2,4; CS = 0,8 моль/л.")
    P(
        doc,
        "CS = 3 k2/(k1+k2) (CA0 − CA) = 3·1,2/3 · (2,4 − CA) = 1,2 (2,4 − CA).\n"
        "0,8 = 1,2 (2,4 − CA) ⇒ CA = 1,733 моль/л.\n"
        "xA = (2,4 − 1,733)/2,4 = 0,28.\n"
        "t = −ln(1,733/2,4)/(1,8+1,2) = 0,11 мин.",
    )
    Ans(doc, "xA = 0,28;  t = 0,11 мин.")

    H2(doc, "Пример 9.  A → R → S")
    P(doc, "k1 = 0,6 мин⁻¹; k2 = 0,8 мин⁻¹; CA0 = 5 моль/л; t = 3 мин.")
    P(
        doc,
        "CA = 5 e^(−0,6·3) = 5 e^(−1,8) = 0,826 моль/л;  xA = 0,835.\n"
        "CR = 5·0,6/(0,8−0,6) (e^−1,8 − e^−2,4) = 15·(0,1653 − 0,0907) = 1,12 моль/л.\n"
        "CS = CA0 − CA − CR = 5 − 0,826 − 1,12 = 3,05 моль/л.",
    )
    Ans(doc, "CR = 1,11 моль/л;  CS = 3,06 моль/л;  xA = 0,835.")

    H2(doc, "Пример 10.  A → R;  A → S")
    P(
        doc,
        "k1 = 10⁻³ с⁻¹; k2 = 10⁻² с⁻¹; CA0 = 2; CS = 0,5; CR = 0,05 моль/л.",
    )
    P(
        doc,
        "Проверка: CS/CR = k2/k1 = 10,  0,5/0,05 = 10.\n"
        "CA0 − CA = CR + CS = 0,55 ⇒ CA = 1,45 моль/л;  xA = 0,275.\n"
        "t = −ln(1,45/2)/(0,001+0,010) = 29,23 с.\n"
        "wA = −(k1+k2)CA = −0,011·1,45 = −0,016 моль/(л·с);\n"
        "wR = k1 CA = 0,00145;  wS = k2 CA = 0,0145 моль/(л·с).",
    )
    Ans(doc, "xA = 0,275;  t = 29,23 с;  wA = −0,016;  wR = 0,00145;  wS = 0,0145 моль/(л·с).")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUT)
    shutil.copyfile(OUT, OUT_CYR)
    print("saved", OUT, OUT_CYR)


if __name__ == "__main__":
    build()
