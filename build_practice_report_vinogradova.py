def set_run_font(run, name="Times New Roman", size=14, bold=None):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold


def add_para(doc, text, *, align=WD_ALIGN_PARAGRAPH.JUSTIFY, bold=False,
             size=14, space_after=0, space_before=0, first_line=True):
    p = doc.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(space_before)
    pf.line_spacing = 1.15
    if first_line and align == WD_ALIGN_PARAGRAPH.JUSTIFY:
        pf.first_line_indent = Cm(1.25)
    else:
        pf.first_line_indent = Cm(0)
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold)
    return p


def add_heading_custom(doc, text, level=1):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    pf = p.paragraph_format
    pf.space_before = Pt(12 if level == 1 else 8)
    pf.space_after = Pt(6)
    pf.first_line_indent = Cm(0)
    pf.line_spacing = 1.15
    run = p.add_run(text)
    set_run_font(run, size=14, bold=True)
    return p


def add_bullet(doc, text):
    p = doc.add_paragraph(style="List Paragraph")
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf = p.paragraph_format
    pf.space_after = Pt(2)
    pf.space_before = Pt(0)
    pf.line_spacing = 1.15
    # clear default runs
    if p.runs:
        p.runs[0].text = text
        set_run_font(p.runs[0], size=14)
    else:
        run = p.add_run(text)
        set_run_font(run, size=14)
    return p


def copy_table(src_table, dst_doc):
    """Deep-copy a table XML into destination document."""
    tbl = deepcopy(src_table._tbl)
    dst_doc._body._body.append(tbl)
    return dst_doc.tables[-1]


def replace_in_table_cell(cell, old, new):
    for p in cell.paragraphs:
        for r in p.runs:
            if old in r.text:
                r.text = r.text.replace(old, new)


def set_cell_text(cell, text, bold=False, size=11):
    # clear
    for p in cell.paragraphs:
        for r in p.runs:
            r.text = ""
    p = cell.paragraphs[0]
    if not p.runs:
        run = p.add_run(text)
    else:
        run = p.runs[0]
        run.text = text
    set_run_font(run, size=size, bold=bold)
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT


