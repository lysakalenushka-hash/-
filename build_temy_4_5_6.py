def _clear_body(doc: Document) -> None:
    body = doc.element.body
    for child in list(body):
        if child.tag != qn("w:sectPr"):
            body.remove(child)


def _set_run_font(run, *, size=None, bold=None, name="Arial"):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run._element.rPr.rFonts.set(qn("w:cs"), name)
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold
    run.font.color.rgb = RGBColor(0, 0, 0)


def add_module(doc: Document, text: str = "Модуль 1") -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    _set_run_font(r, size=16, bold=True)
    pPr = p._p.get_or_add_pPr()
    jc = pPr.find(qn("w:jc"))
    if jc is None:
        jc = OxmlElement("w:jc")
        pPr.append(jc)
    jc.set(qn("w:val"), "center")


def add_title(doc: Document, text: str) -> None:
    p = doc.add_paragraph(style="Title")
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    _set_run_font(r, size=14, bold=False)


def add_h2(doc: Document, text: str) -> None:
    p = doc.add_paragraph(style="Heading 2")
    r = p.add_run(text)
    _set_run_font(r, bold=None)


def add_h3(doc: Document, text: str) -> None:
    p = doc.add_paragraph(style="Heading 3")
    r = p.add_run(text)
    _set_run_font(r, size=12, bold=True)


def add_body(doc: Document, text: str) -> None:
    p = doc.add_paragraph(style="Normal (Web)")
    r = p.add_run(text)
    _set_run_font(r)


def add_items(doc: Document, items: list[str]) -> None:
    for text in items:
        p = doc.add_paragraph(style="Normal (Web)")
        pPr = p._p.get_or_add_pPr()
        numPr = OxmlElement("w:numPr")
        ilvl = OxmlElement("w:ilvl")
        ilvl.set(qn("w:val"), "0")
        nid = OxmlElement("w:numId")
        nid.set(qn("w:val"), "10")
        numPr.append(ilvl)
        numPr.append(nid)
        pPr.append(numPr)
        r = p.add_run(text)
        _set_run_font(r)


def factor_block(
    doc: Document,
    heading: str,
    h3_cause: str,
    causes: list[str],
    effects: list[str] | str,
    measures_intro: str | None,
    measures: list[str] | str,
) -> None:
    add_h2(doc, heading)
    add_h3(doc, h3_cause)
    if isinstance(causes, list) and len(causes) == 1 and not causes[0].endswith(";"):
        add_body(doc, causes[0])
    else:
        for c in causes:
            if c.endswith(":") or (c.endswith(".") and len(c) > 80):
                add_body(doc, c)
            else:
                # mix of intro sentences and list handled by caller
                add_body(doc, c)
    add_h3(doc, "Возможные последствия")
    if isinstance(effects, str):
        add_body(doc, effects)
    else:
        add_items(doc, effects)
    add_h3(doc, "Меры предупреждения")
    if measures_intro:
        add_body(doc, measures_intro)
    if isinstance(measures, str):
        add_body(doc, measures)
    else:
        add_items(doc, measures)


def write_doc(path: Path, title: str, builder) -> None:
    shutil.copy(TEMPLATE, path)
    doc = Document(str(path))
    _clear_body(doc)
    add_module(doc)
    add_title(doc, title)
    builder(doc)
    doc.save(str(path))
    print("wrote", path, "paras", len(doc.paragraphs))


