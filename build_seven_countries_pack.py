def shade(cell, fill="1F4E79"):
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), fill)
    shd.set(qn("w:val"), "clear")
    cell._tc.get_or_add_tcPr().append(shd)


def add_table(doc, headers, rows, header_fill="1F4E79"):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = ""
        run = cell.paragraphs[0].add_run(h)
        set_run_font(run, size=10, bold=True, color=RGBColor(0xFF, 0xFF, 0xFF))
        shade(cell, header_fill)
    for r, row in enumerate(rows, start=1):
        for c, val in enumerate(row):
            cell = table.rows[r].cells[c]
            cell.text = ""
            run = cell.paragraphs[0].add_run(str(val))
            set_run_font(run, size=10, bold=(c == 0))
    doc.add_paragraph()
    return table


def note_analog(doc, text: str):
    p = doc.add_paragraph()
    run = p.add_run("Пометка о статусе практики. ")
    set_run_font(run, size=11, bold=True, color=NAVY)
    run2 = p.add_run(text)
    set_run_font(run2, size=11, color=GRAY)


def save(doc, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(path)
    return path


