def build_xlsx() -> Path:
    wb = Workbook()
    header_fill = PatternFill("solid", fgColor="1F4E79")
    header_font = Font(bold=True, color="FFFFFF", name="Calibri", size=10)
    wrap = Alignment(wrap_text=True, vertical="top")
    thin = Border(
        left=Side(style="thin", color="BFBFBF"),
        right=Side(style="thin", color="BFBFBF"),
        top=Side(style="thin", color="BFBFBF"),
        bottom=Side(style="thin", color="BFBFBF"),
    )

    def style_header(ws, row, cols):
        for c in range(1, cols + 1):
            cell = ws.cell(row, c)
            cell.fill = header_fill
            cell.font = header_font
            cell.alignment = wrap
            cell.border = thin

    def dump_rows(ws, start, rows):
        for r, row in enumerate(rows, start=start):
            for c, val in enumerate(row, start=1):
                cell = ws.cell(r, c, val)
                cell.alignment = wrap
                cell.border = thin
                cell.font = Font(name="Calibri", size=10)
            ws.row_dimensions[r].height = 72

    ws = wb.active
    ws.title = "A_ЭДО_в_целом"
    headers = [
        "Страна",
        "Кластер",
        "Основные акты",
        "Юридическая сила",
        "Модель подписи",
        "Доверие / УЦ",
        "Трансграничность",
        "Особенность",
    ]
    for i, h in enumerate(headers, start=1):
        ws.cell(1, i, h)
    style_header(ws, 1, len(headers))
    rows = []
    for c in COUNTRIES:
        d = c["edo"]
        rows.append(
            [c["name"], c["cluster"], d["acts"], d["legal_force"], d["signature"], d["trust"], d["crossborder"], d["feature"]]
        )
    rows.append(
        [
            "Российская Федерация",
            "PKI / КЭДО",
            "63‑ФЗ; ст. 22.1–22.3 ТК; 315‑ФЗ (04.08.2026); Решение ЕЭК № 120",
            "Эл. документ с ЭП при соблюдении вида подписи и закона/соглашения",
            "ПЭП / УНЭП / УКЭП",
            "Аккредитованные УЦ, операторы ЭДО, УЦ ФНС",
            "Ст. 7 63‑ФЗ, договоры, ДТС ЕАЭС",
            "Отдельный КЭДО; ст. 22.1(3) выводит журналы инструктажа и акты НС",
        ]
    )
    dump_rows(ws, 2, rows)

    ws2 = wb.create_sheet("B_ЭДО_в_ОТ")
    headers2 = [
        "Страна",
        "Акты ОТ",
        "Можно ли e‑журнал / e‑учёт обучения",
        "Подпись",
        "Сравнение с ст. 22.1(3) ТК РФ",
    ]
    for i, h in enumerate(headers2, start=1):
        ws2.cell(1, i, h)
    style_header(ws2, 1, len(headers2))
    rows2 = []
    for c in COUNTRIES:
        d = c["ot"]
        rows2.append([c["name"], d["acts"], d["legal_force"], d["signature"], d["compare"][1] if len(d["compare"]) > 1 else d["compare"][0]])
    rows2.append(
        [
            "Российская Федерация",
            "ТК ст. 22.1(3); ПП 2464",
            "Нет в контуре КЭДО: журналы инструктажа и акты НС исключены",
            "На практике бумажный журнал",
            "Национальный запрет носителя, не вытекающий из eIDAS/113‑З",
        ]
    )
    dump_rows(ws2, 2, rows2)

    ws3 = wb.create_sheet("C_Судебная_практика")
    headers3 = ["Страна", "Срез", "Тип", "Суд", "Цитата", "Сюжет", "Аналогия?"]
    for i, h in enumerate(headers3, start=1):
        ws3.cell(1, i, h)
    style_header(ws3, 1, len(headers3))
    rows3 = []
    for c in COUNTRIES:
        for kind, case in (("ЭДО", c["case_edo"]), ("ОТ", c["case_ot"])):
            rows3.append(
                [
                    c["name"],
                    kind,
                    "аналогия" if case["analog"] else "прямая",
                    case["court"],
                    case["cite"],
                    case["title"],
                    "да" if case["analog"] else "нет",
                ]
            )
    dump_rows(ws3, 2, rows3)

    ws4 = wb.create_sheet("Легенда")
    ws4["A1"] = "Легенда пакета семи стран"
    ws4["A1"].font = Font(bold=True, size=14, color="1F4E79", name="Calibri")
    notes = [
        ("Прямая практика", "Опубликованное дело / устойчивая линия судов именно об электронном документе, подписи или допустимости e‑доказательств."),
        ("Аналогия", "Прямого дела об электронном журнале ОТ нет; взята ближайшая практика об обучении, бремени мер безопасности или форме подписи. Помечено в каждом файле."),
        ("Не вымышлено", "Номера дел (BGH VIII ZR 155/23, BAG 1 ABR 104/09, Cass. 24‑21.034, [2025] KEELC 392 и др.) проверены по первичным/официальным публикациям."),
        ("РФ", "Точка сравнения: 63‑ФЗ, ТК 22.1–22.3, ПП 2464, 315‑ФЗ от 04.08.2026."),
        ("Главный вывод", "РФ уникальна запретом журналов инструктажа и актов НС в КЭДО. Беларусь — ближайший положительный образец. Сербия — точечный бумажный Form 6."),
    ]
    ws4["A3"] = "Понятие"
    ws4["B3"] = "Смысл"
    style_header(ws4, 3, 2)
    dump_rows(ws4, 4, notes)

    for wsx, widths in (
        (ws, [18, 22, 42, 42, 36, 32, 32, 40]),
        (ws2, [18, 50, 50, 42, 42]),
        (ws3, [16, 10, 12, 36, 50, 50, 12]),
        (ws4, [22, 100]),
    ):
        for i, w in enumerate(widths, start=1):
            wsx.column_dimensions[get_column_letter(i)].width = w
        wsx.freeze_panes = "B2"
        wsx.row_dimensions[1].height = 28

    path = PACK / "05_Матрицы" / "Матрица_7стран_ЭДО_ОТ_практика.xlsx"
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


