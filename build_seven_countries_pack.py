def zip_pack() -> Path:
    zip_path = Path(ZIP_NAME)
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for p in PACK.rglob("*"):
            if p.is_file():
                zf.write(p, arcname=str(p).replace("\\", "/"))
    return zip_path


def main():
    if PACK.exists():
        import shutil

        shutil.rmtree(PACK)
    PACK.mkdir(parents=True)
    paths = build_readme()
    for c in COUNTRIES:
        paths.append(build_edo_doc(c))
        paths.append(build_ot_doc(c))
        paths.append(build_case_doc(c, "edo"))
