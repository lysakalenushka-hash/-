RED = RGBColor(0xE3, 0x06, 0x13)
DARK = RGBColor(0x1A, 0x1A, 0x1A)
GRAY = RGBColor(0x6B, 0x72, 0x80)
AMBER = RGBColor(0xF5, 0x9E, 0x0B)


def set_run(run, size_pt, bold=False, color=DARK):
    run.font.name = "Inter"
    run.font.size = Pt(size_pt)
    run.font.bold = bold
    run.font.color.rgb = color


def set_text(shape, text, size_pt=13, bold=False, color=DARK):
    tf = shape.text_frame
    tf.clear()
    p = tf.paragraphs[0]
    r = p.add_run()
    r.text = text
    set_run(r, size_pt, bold=bold, color=color)


def text_shapes(slide):
    return [s for s in slide.shapes if s.has_text_frame and s.text_frame.text.strip()]


def all_text_shapes(slide):
    return [s for s in slide.shapes if s.has_text_frame]


def clear_slides(prs):
    while len(prs.slides) > 0:
        r_id = prs.slides._sldIdLst[0].rId
        prs.part.drop_rel(r_id)
        del prs.slides._sldIdLst[0]


def make_slide(prs, shape_elements):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    for shape in list(slide.shapes):
        shape.element.getparent().remove(shape.element)
    for element in shape_elements:
        slide.shapes._spTree.insert_element_before(deepcopy(element), "p:extLst")
    return slide


def update_pages(prs):
    total = len(prs.slides)
    for i, slide in enumerate(prs.slides, 1):
        updated = False
        for sh in all_text_shapes(slide):
            if sh.top is not None and sh.left is not None:
                if sh.top > Emu(6200000) and sh.left > Emu(8000000):
                    set_text(sh, f"{i:02d} / {total:02d}", 9, True, RED)
                    updated = True
                    break
            t = sh.text_frame.text.strip()
            if " / " in t:
                left, right = [x.strip() for x in t.split(" / ", 1)]
                if left.isdigit() and right.isdigit():
                    set_text(sh, f"{i:02d} / {total:02d}", 9, True, RED)
                    updated = True
                    break
        if not updated:
            box = slide.shapes.add_textbox(
                Emu(10271455), Emu(6492240), Emu(1200000), Emu(228600)
            )
            set_text(box, f"{i:02d} / {total:02d}", 9, True, RED)


def content_shapes(slide):
    shapes = sorted(all_text_shapes(slide), key=lambda s: (s.top or 0, s.left or 0))
    return [
        s
        for s in shapes
        if not (
            s.top is not None
            and s.left is not None
            and s.top > Emu(6200000)
            and s.left > Emu(8000000)
        )
    ]


def fill_text_slide(slide, section, title, intro, body, note=None):
    shapes = content_shapes(slide)
    # Clear every content shape first — prevents leftover template text
    for sh in shapes:
        set_text(sh, "", 12, False, DARK)
    set_text(shapes[0], section, 11, True, RED)
    set_text(shapes[1], title, 26, True, DARK)
    set_text(shapes[2], intro, 12, False, GRAY)
    set_text(shapes[3], body, 13, False, DARK)
    if len(shapes) > 4 and shapes[4].top < Emu(6200000):
        set_text(shapes[4], note or "", 12, True, AMBER if note else GRAY)


def _set_bullet_spacing(paragraph, before_pts=80):
    pPr = paragraph._p.get_or_add_pPr()
    for old in list(pPr):
        if old.tag.endswith("spcBef") or old.tag.endswith("spcAft"):
            pPr.remove(old)
    spcBef = SubElement(pPr, qn("a:spcBef"))
    spcPts = SubElement(spcBef, qn("a:spcPts"))
    spcPts.set("val", str(before_pts))


def fill_bullet_slide(slide, section, title, intro, items, note=None, start_num=1):
    """Write ALL items as bullets into the tallest body shape — no truncation."""
    shapes = content_shapes(slide)
    for sh in shapes:
        set_text(sh, "", 12, False, DARK)
    set_text(shapes[0], section, 11, True, RED)
    set_text(shapes[1], title, 24, True, DARK)
    set_text(shapes[2], intro, 12, False, GRAY)

    body = max(shapes[3:], key=lambda s: s.height or 0)
    for sh in shapes[3:]:
        if sh is body:
            continue
        if sh.top < Emu(6200000):
            set_text(sh, "", 11, False, GRAY)

    size = 14 if len(items) <= 5 else (13 if len(items) <= 7 else 11)
    tf = body.text_frame
    tf.clear()
    for i, item in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = ""
        p.level = 0
        run = p.add_run()
        run.text = f"{start_num + i:02d}.  {item}"
        set_run(run, size, False, DARK)
        _set_bullet_spacing(p, 60 if len(items) > 7 else (70 if len(items) > 6 else 90))

    if note:
        note_shape = None
        for sh in shapes:
            if sh is body:
                continue
            if sh.top > Emu(5400000) and sh.left < Emu(9000000) and sh.top < Emu(6200000):
                note_shape = sh
                break
        if note_shape:
            set_text(note_shape, note, 12, True, AMBER)
        else:
            box = slide.shapes.add_textbox(
                Emu(548640), Emu(5850000), Emu(10000000), Emu(400000)
            )
            set_text(box, note, 12, True, AMBER)


def add_image(slide, path, bottom=False):
    path = Path(path)
    if not path.exists() or path.stat().st_size < 5000:
        return
    if bottom:
        slide.shapes.add_picture(
            str(path), Emu(731520), Emu(4200000), width=Emu(10700000), height=Emu(1800000)
        )
    else:
        slide.shapes.add_picture(
            str(path), Emu(7000000), Emu(1400000), width=Emu(4800000), height=Emu(4200000)
        )


def chunks(items, n):
    for i in range(0, len(items), n):
        yield items[i : i + n]


