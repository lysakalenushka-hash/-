def style_header(cell):
    cell.fill = HEADER_FILL
    cell.font = HEADER_FONT
    cell.alignment = Alignment(wrap_text=True, horizontal="center", vertical="center")
    cell.border = THIN


def autosize(ws, widths: dict):
    for col, w in widths.items():
        ws.column_dimensions[col].width = w


def main():
    wb = Workbook()

    # ===== 1. Реестр дел =====
    ws = wb.active
    ws.title = "Судебная практика"
    headers = [
        "№",
        "Год",
        "Номер дела / акт",
        "Суд",
        "Категория",
        "Сценарий (что с подписью/датой)",
        "Момент подписи / даты",
        "Предмет спора",
        "Исход",
        "На чьей стороне",
        "Практический вывод",
        "Группа сравнения",
        "Ссылка",
        "Тип в подборке",
    ]
    for col, h in enumerate(headers, 1):
        style_header(ws.cell(1, col, h))
    ws.row_dimensions[1].height = 40
    ws.freeze_panes = "C2"

    for ri, c in enumerate(CASES, 2):
        vals = [
            c["n"],
            c["year"],
            c["number"],
            c["court"],
            c["category"],
            c["scenario"],
            c["timing"],
            c["issue"],
            c["outcome"],
            c["side"],
            c["conclusion"],
            c["group"],
            c["link"],
            c["source"],
        ]
        for ci, v in enumerate(vals, 1):
            cell = ws.cell(ri, ci, v)
            cell.alignment = Alignment(wrap_text=True, vertical="top")
            cell.border = THIN
            if ci == 5:
                cell.fill = GROUP_FILLS.get(c["category"], PatternFill())
            if ci == 10:
                side_l = str(v).lower()
                if "работодатель" in side_l and "гит" not in side_l and "проигра" not in c["outcome"].lower():
                    if "выиграл" in c["outcome"].lower() or "допустим" in c["outcome"].lower() or "отсутствует" in c["outcome"].lower():
                        cell.fill = YES_FILL
                    else:
                        cell.fill = NO_FILL
                elif "гит" in side_l or "работник" in side_l:
                    cell.fill = NO_FILL if "работник" not in side_l else YES_FILL
                else:
                    cell.fill = MIX_FILL
        ws.row_dimensions[ri].height = 70

    autosize(
        ws,
        {
            "A": 4,
            "B": 6,
            "C": 42,
            "D": 28,
            "E": 28,
            "F": 40,
            "G": 32,
            "H": 34,
            "I": 28,
            "J": 18,
            "K": 36,
            "L": 28,
            "M": 35,
            "N": 22,
        },
    )

    # ===== 2. Пары =====
    ws2 = wb.create_sheet("Пары и противоположности")
    for col, h in enumerate(
        ["Группа", "Общие факты", "Дело / позиция А", "Дело / позиция Б", "Что решило / в чём разница"],
        1,
    ):
        style_header(ws2.cell(1, col, h))
    ws2.row_dimensions[1].height = 35
