def write_md(path: Path) -> None:
    lines = [
        "# Навигатор по нарушениям для тренинга",
        "",
        "Стандарт обучения: методический документ М-16.01.10-14 «О порядке обучения по охране труда и проверки знания требований охраны труда работников Дочерних Обществ ПАО «Газпром нефть» (версия для обсуждения).",
        "",
        "Матрица ролей: «Матрица ответственности. Проведение обучения по охране труда и проверки знания требований охраны труда работников».",
        "",
        "Как пользоваться. В колонке «Название нарушения» — что искать в задании. В колонке «Ресурсы» — какие материалы держать под рукой. В колонке «Разделы стандарта обучения» — куда открыть М-16.01.10-14, чтобы подтвердить нарушение и выполнить задание. Кейс заданий 1 и 5 разбирают на работе подрядчика на площадке ДО, не на работниках ПАО «Газпром нефть».",
        "",
        "| № | Название нарушения | Ресурсы | Разделы стандарта обучения |",
        "| --- | --- | --- | --- |",
    ]
    for n, name, res, sec in ROWS:
        def cell(value: str) -> str:
            return value.replace("|", "\\|")

        lines.append(f"| {n} | {cell(name)} | {cell(res)} | {cell(sec)} |")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def write_xlsx(path: Path) -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "Навигатор"
    headers = ["№", "Название нарушения", "Ресурсы", "Разделы стандарта обучения"]
    ws.append(headers)
    for row in ROWS:
        ws.append(list(row))

    header_fill = PatternFill("solid", fgColor="1F4E79")
    header_font = Font(name="Calibri", bold=True, color="FFFFFF", size=12)
    body_font = Font(name="Calibri", size=11)
    alt_fill = PatternFill("solid", fgColor="F3F6F9")
    thin = Border(
        left=Side(style="thin", color="D0D7DE"),
        right=Side(style="thin", color="D0D7DE"),
        top=Side(style="thin", color="D0D7DE"),
        bottom=Side(style="thin", color="D0D7DE"),
    )
    wrap = Alignment(wrap_text=True, vertical="top")
    for col in range(1, 5):
        cell = ws.cell(1, col)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(wrap_text=True, vertical="center")
        cell.border = thin
    for r in range(2, ws.max_row + 1):
        for c in range(1, 5):
            cell = ws.cell(r, c)
            cell.font = body_font
            cell.alignment = wrap
            cell.border = thin
            if r % 2 == 0:
                cell.fill = alt_fill
        ws.row_dimensions[r].height = 78
    ws.row_dimensions[1].height = 24
    widths = [6, 62, 48, 78]
    for i, width in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = width
    ws.auto_filter.ref = f"A1:D{ws.max_row}"
    ws.freeze_panes = "A2"
    ws.page_setup.orientation = "landscape"
    ws.page_setup.paperSize = ws.PAPERSIZE_A3
    ws.page_setup.fitToPage = True
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.page_margins = PageMargins(left=0.4, right=0.4, top=0.5, bottom=0.5)
    ws.oddHeader.left.text = "М-16.01.10-14. Навигатор для участников тренинга"
    ws.oddFooter.right.text = "Стр. &P"
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.print_title_rows = "1:1"
    ws.sheet_view.showGridLines = False
    wb.save(path)


