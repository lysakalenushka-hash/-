def build_all_modules():
    OUT_DIR.mkdir(exist_ok=True)
    created = []
    for mod in MODULES:
        slug = MODULE_SLUGS[mod["num"]]
        docx_path = OUT_DIR / f"Б.7.5_{slug}.docx"
        pptx_path = OUT_DIR / f"Б.7.5_{slug}.pptx"
        build_module_docx(mod, docx_path)
        render_module_pptx(mod["num"], pptx_path)
        created.append((docx_path, pptx_path))
    return created


