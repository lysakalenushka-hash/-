OUTPUT = "/workspace/Презентация_Тема_2.pptx"

# Colors
DARK_BLUE = RGBColor(0, 51, 102)
ACCENT = RGBColor(0, 102, 153)
WHITE = RGBColor(255, 255, 255)
TEXT = RGBColor(40, 40, 40)
LIGHT_BG = RGBColor(245, 248, 252)


def set_slide_bg(slide, color):
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = color


def add_title_bar(slide, title_text, subtitle=None):
    shape = slide.shapes.add_shape(1, Inches(0), Inches(0), Inches(10), Inches(1.15))
    shape.fill.solid()
    shape.fill.fore_color.rgb = DARK_BLUE
    shape.line.fill.background()
    tf = shape.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.text = title_text
    p.font.size = Pt(24)
    p.font.bold = True
    p.font.color.rgb = WHITE
    p.alignment = PP_ALIGN.LEFT
    tf.margin_left = Inches(0.35)
    tf.margin_top = Inches(0.15)
    if subtitle:
        box = slide.shapes.add_textbox(Inches(0.35), Inches(1.25), Inches(9.3), Inches(0.4))
        p2 = box.text_frame.paragraphs[0]
        p2.text = subtitle
        p2.font.size = Pt(12)
        p2.font.color.rgb = ACCENT
        p2.font.italic = True
        content_top = Inches(1.75)
    else:
        content_top = Inches(1.35)
    return content_top


def add_bullets(slide, items, top, height=Inches(5.5), font_size=16, title=None):
    if title:
        tbox = slide.shapes.add_textbox(Inches(0.35), top, Inches(9.3), Inches(0.45))
        p = tbox.text_frame.paragraphs[0]
        p.text = title
        p.font.size = Pt(15)
        p.font.bold = True
        p.font.color.rgb = DARK_BLUE
        top += Inches(0.5)

    box = slide.shapes.add_textbox(Inches(0.35), top, Inches(9.3), height)
    tf = box.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = MSO_ANCHOR.TOP

    for i, item in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = item
        p.level = 0
        p.font.size = Pt(font_size)
        p.font.color.rgb = TEXT
        p.space_after = Pt(8)
        p.line_spacing = 1.15


