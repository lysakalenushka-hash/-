def build():
    prs = Presentation()
    prs.slide_width = Inches(10)
    prs.slide_height = Inches(7.5)

    for spec in SLIDES:
        slide = prs.slides.add_slide(prs.slide_layouts[6])
        set_slide_bg(slide, LIGHT_BG)

        if spec.get("type") == "title":
            bar = slide.shapes.add_shape(1, Inches(0), Inches(2.2), Inches(10), Inches(2.8))
            bar.fill.solid()
            bar.fill.fore_color.rgb = DARK_BLUE
            bar.line.fill.background()
            tf = bar.text_frame
            tf.word_wrap = True
            p = tf.paragraphs[0]
            p.text = spec["title"]
            p.font.size = Pt(32)
            p.font.bold = True
            p.font.color.rgb = WHITE
            p.alignment = PP_ALIGN.CENTER
            tf.margin_top = Inches(0.5)

            sub = slide.shapes.add_textbox(Inches(0.5), Inches(5.2), Inches(9), Inches(1.2))
            sp = sub.text_frame.paragraphs[0]
            sp.text = spec["subtitle"]
            sp.font.size = Pt(16)
            sp.font.color.rgb = TEXT
            sp.alignment = PP_ALIGN.CENTER

            foot = slide.shapes.add_textbox(Inches(0.5), Inches(6.6), Inches(9), Inches(0.5))
            fp = foot.text_frame.paragraphs[0]
            fp.text = spec.get("footer", "")
            fp.font.size = Pt(11)
            fp.font.color.rgb = ACCENT
            fp.alignment = PP_ALIGN.CENTER
            continue

        top = add_title_bar(slide, spec["title"], spec.get("subtitle"))
        add_bullets(
            slide,
            spec["items"],
            top,
            font_size=spec.get("font_size", 15),
        )

    prs.save(OUTPUT)
    print(f"Saved: {OUTPUT}")


if __name__ == "__main__":
    build()
