        ("01", "По назначению", "Объект используют только так, как задано проектом и документацией."),
        ("02", "Конструкции", "Нельзя самовольно изменять конструкции, ограждения и нагрузки."),
        ("03", "Проходы", "Проходы и пути эвакуации должны оставаться свободными."),
