    head(s, "РАЗДЕЛ 6  ·  ПОЖАРНАЯ БЕЗОПАСНОСТЬ ПЛОЩАДОК", "Откуда начинается пожар")
    picture(s, ASSETS / "iso_f001.png", 9.55, 1.35, 2.95, 2.95)
    picture(s, ASSETS / "ext_ed.jpg", 9.7, 4.45, 2.65, 2.15)
    numbered(s, [
        "Пыль и горючие отходы.",
        "Захламлённые проходы.",
        "Курение и открытый огонь.",
        "Временные нагреватели.",
        "Огневые работы вне установленного порядка.",
        "Итог: возгорание отложений, быстрый ход огня по пыли, закрытая эвакуация, нет доступа к огнетушителю.",
    ], t=1.4, w=8.5)
    ft(s, 15)

    # 16 — меры ПБ
    s = new_slide(prs)
    head(s, "РАЗДЕЛ 6  ·  ПОЖАРНАЯ БЕЗОПАСНОСТЬ ПЛОЩАДОК", "Меры предупреждения")
    picture(s, ASSETS / "gost_e03.png", 9.5, 1.4, 3.15, 2.4)
    picture(s, ASSETS / "iso_p080.png", 9.5, 4.0, 3.15, 2.5)
    numbered(s, [
        "Содержать проходы и подъезды свободными.",
        "Обеспечивать доступ к средствам пожаротушения.",
        "Удалять пыль и горючие отходы установленным безопасным способом.",
        "Курить, применять открытый огонь и выполнять огневые работы только в предусмотренных местах и порядке.",
    ], t=1.45, w=8.5)
    ft(s, 16)

