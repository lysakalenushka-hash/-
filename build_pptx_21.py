#!/usr/bin/env python3
"""Тема 2.1 — строго по учебному файлу, с схемами и фото."""

from pptx_style import (
    ASSETS, NAVY, INK, MUTED, WHITE, PALE, SERIF, SOFT,
    add_text, add_paras, bar, cards, contents, cover, footer, new_prs, new_slide,
    numbered, picture, rect,
)

MOD = "МОДУЛЬ 2"
TOPIC = "ТЕМА 2.1"
TOTAL = 18


def ft(s, n):
    footer(s, n, TOTAL, TOPIC, MOD)


def head(s, kicker, title):
    add_text(s, 0.62, 0.32, 12, 0.28, kicker, size=12, color=MUTED, bold=True)
    add_text(s, 0.6, 0.55, 12.2, 0.55, title, size=26, color=NAVY, name=SERIF)
    bar(s, 0.62, 1.16, 1.85)


def build():
    prs = new_prs()
    k = dict(topic=TOPIC, total=TOTAL, module=MOD)

    cover(
        prs,
        photo=ASSETS / "elev_ed.jpg",
        title="Здания, сооружения,\nпомещения\nи производственные площадки",
        subtitle="Объект используют только по назначению.\nКонструкции, ограждения и нагрузки не меняют на смене.",
        **k,
    )

    contents(
        prs,
        items=[
            ("01", "Общие положения"),
            ("02", "Производственные здания и сооружения"),
            ("03", "Полы, проходы и рабочие места"),
            ("04", "Освещение, вентиляция и инженерные системы"),
            ("05", "Признаки повреждения конструкций"),
            ("06", "Пожарная безопасность площадок"),
            ("07", "Общие меры предупреждения"),
        ],
        **k,
    )

    # 3 — общие положения
