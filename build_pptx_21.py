    s = new_slide(prs)
    head(s, "РАЗДЕЛ 5  ·  ПОВРЕЖДЕНИЕ КОНСТРУКЦИЙ", "Признаки опасного состояния")
    picture(s, ASSETS / "crack_ed.jpg", 8.35, 1.35, 4.35, 2.8)
