    ft(s, 13)

    # 14 — ещё можно ходить
    s = new_slide(prs)
    rect(s, 0.6, 1.35, 12.1, 5.15, NAVY, adj=0.05)
    add_text(s, 0.9, 1.7, 11.4, 0.4, "РАЗДЕЛ 5  ·  РЕАКЦИЯ", size=13, color=SOFT, bold=True)
    add_text(
        s, 0.9, 2.2, 11.4, 2.2,
        "«Ещё можно ходить» — не решение. Самостоятельная оценка не заменяет решение ответственного лица.",
        size=26, color=WHITE, name=SERIF,
    )
    add_text(
        s, 0.9, 4.6, 11.4, 1.4,
        "В пределах полномочий ограничить доступ, предупредить людей и сообщить ответственному лицу.",
        size=18, color=SOFT,
    )
    ft(s, 14)

