    picture(s, ASSETS / "eexit_ed.jpg", 7.85, 4.9, 4.9, 1.75)
    add_paras(s, 0.6, 1.4, 7.0, 5.2, [
        "Скольжение, спотыкание, падение.",
        "Травмы при перемещении грузов.",
        "Невозможно быстро покинуть опасную зону.",
        "Закрыт доступ к аварийным выключателям, огнетушителям и электрощитам.",
        "Полы, лестницы и площадки — в безопасном состоянии.",
        "Просыпи, разливы и наледь убирать по установленному порядку.",
        "Материалы — только в предназначенных местах.",
        "О повреждении настила, поручней и ступеней — руководителю.",
    ], size=14, spacing=8)
    ft(s, 10)

    # 11 — освещение вентиляция
    s = new_slide(prs)
    head(s, "РАЗДЕЛ 4  ·  ИНЖЕНЕРНЫЕ СИСТЕМЫ", "Освещение, вентиляция, аспирация")
    picture(s, ASSETS / "mill_ed.jpg", 8.25, 1.3, 4.45, 5.35)
    add_paras(s, 0.6, 1.4, 7.4, 5.2, [
        "Освещение должно позволять безопасно выполнять операции и замечать опасные зоны.",
        "Вентиляция и аспирация работают в режимах технологических документов.",
        "Если потемнело — опасность можно не увидеть вовремя.",
        "Если отказала аспирация — накапливается пыль.",
        "Необычный запах, отказ света, повреждение трассы — сообщить руководителю.",
        "Самостоятельно наращивать освещение и менять трассы нельзя.",
    ], size=16, spacing=10)
    ft(s, 11)

    # 12 — сети не опора
    s = new_slide(prs)
    head(s, "РАЗДЕЛ 4  ·  ИНЖЕНЕРНЫЕ СИСТЕМЫ", "Кабель, воздуховод и труба — не ступень")
    picture(s, ASSETS / "schema_eng.png", 0.55, 1.35, 12.2, 5.35)
    ft(s, 12)

