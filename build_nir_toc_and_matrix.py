NAVY = RGBColor(0x1F, 0x4E, 0x79)
GRAY = RGBColor(0x53, 0x53, 0x53)


def set_run(run, size=14, bold=False, color=None, name="Times New Roman"):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    run.bold = bold
    if color is not None:
        run.font.color.rgb = color


def setup_doc() -> Document:
    doc = Document()
    sec = doc.sections[0]
    sec.page_width = Cm(21)
    sec.page_height = Cm(29.7)
    sec.left_margin = Cm(2.5)
    sec.right_margin = Cm(2.0)
    sec.top_margin = Cm(2.0)
    sec.bottom_margin = Cm(2.0)
    styles = doc.styles
    styles["Normal"].font.name = "Times New Roman"
    styles["Normal"]._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    styles["Normal"].font.size = Pt(14)
    styles["Normal"].paragraph_format.line_spacing = 1.5
    styles["Normal"].paragraph_format.space_after = Pt(6)
    for hn, sz in (("Title", 18), ("Heading 1", 16), ("Heading 2", 15), ("Heading 3", 14)):
        st = styles[hn]
        st.font.name = "Times New Roman"
        st._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        st.font.size = Pt(sz)
        st.font.bold = True
        st.font.color.rgb = NAVY
    return doc


def add_title(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    set_run(run, size=18, bold=True, color=NAVY)


def add_center(doc, text, size=12, italic=False):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    set_run(run, size=size, color=GRAY)
    run.italic = italic


def add_h1(doc, text):
    doc.add_heading(text, level=1)


def add_h2(doc, text):
    doc.add_heading(text, level=2)


def add_p(doc, text, indent=True):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.first_line_indent = Cm(1.25)
    run = p.add_run(text)
    set_run(run, size=14)
    return p


def add_bullet(doc, text):
    p = doc.add_paragraph(style="List Bullet")
    run = p.add_run(text)
    set_run(run, size=14)


def add_toc_line(doc, left: str, right: str = "", bold=False, level=0):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.line_spacing = 1.15
    if level == 1:
        p.paragraph_format.left_indent = Cm(0.75)
    elif level == 2:
        p.paragraph_format.left_indent = Cm(1.5)
    elif level == 3:
        p.paragraph_format.left_indent = Cm(2.25)
    run = p.add_run(left)
    set_run(run, size=14, bold=bold)
    if right:
        run2 = p.add_run(f" {right}")
        set_run(run2, size=12, color=GRAY)


