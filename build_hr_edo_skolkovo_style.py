    # force Times on last hyperlink run is hard; Calibri 12 in Times doc is acceptable for URLs


def setup() -> Document:
    doc = Document()
    sec = doc.sections[0]
    sec.page_width = Cm(21)
    sec.page_height = Cm(29.7)
    sec.left_margin = Cm(3.0)
    sec.right_margin = Cm(1.5)
    sec.top_margin = Cm(2.0)
    sec.bottom_margin = Cm(2.0)
    styles = doc.styles
    styles["Normal"].font.name = "Times New Roman"
    styles["Normal"]._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    styles["Normal"].font.size = Pt(14)
    styles["Normal"].paragraph_format.line_spacing = 1.5
    styles["Normal"].paragraph_format.first_line_indent = Cm(1.25)
    styles["Normal"].paragraph_format.space_after = Pt(0)
    for hn, sz in (("Title", 16), ("Heading 1", 14), ("Heading 2", 14), ("Heading 3", 14)):
        st = styles[hn]
        st.font.name = "Times New Roman"
        st._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        st.font.size = Pt(sz)
        st.font.bold = True
        st.font.color.rgb = NAVY
    return doc


def h1(doc, text):
    p = doc.add_heading(text, level=1)
    for r in p.runs:
        set_run(r, size=14, bold=True, color=NAVY)
    p.paragraph_format.first_line_indent = Cm(0)


def h2(doc, text):
    p = doc.add_heading(text, level=2)
    for r in p.runs:
        set_run(r, size=14, bold=True, color=NAVY)
    p.paragraph_format.first_line_indent = Cm(0)


def para(doc, text, indent=True):
    p = doc.add_paragraph()
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.first_line_indent = Cm(1.25) if indent else Cm(0)
    run = p.add_run(text)
    set_run(run, size=14)
    return p


def bullet(doc, text):
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.line_spacing = 1.15
    run = p.add_run(text)
    set_run(run, size=14)
    return p


def check(doc, sources):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(8)
    run = p.add_run("Проверить: ")
    set_run(run, size=11, italic=True, color=GRAY)
    for i, (name, url) in enumerate(sources):
        if i:
            sep = p.add_run("  ·  ")
            set_run(sep, size=11, color=GRAY)
        add_hl(p, name, url, size=11)


def caption(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(0)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    set_run(run, size=12, italic=True)


